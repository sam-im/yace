// Chip8's 4096-bytes of memory

// First 512-bytes are reserved for the interpreter
pub const ROM_START_ADDR: usize = 0x200;
// Can be placed anywhere in the first 512 bytes
// But for some reason 0x50 is popular
pub const FONTSET_START_ADDR: usize = 0x50;
// Each glyphs is represented by 5 bytes
pub const FONTSET: [u8; 80] = [
    0xF0, 0x90, 0x90, 0x90, 0xF0, // 0
    0x20, 0x60, 0x20, 0x20, 0x70, // 1
    0xF0, 0x10, 0xF0, 0x80, 0xF0, // 2
    0xF0, 0x10, 0xF0, 0x10, 0xF0, // 3
    0x90, 0x90, 0xF0, 0x10, 0x10, // 4
    0xF0, 0x80, 0xF0, 0x10, 0xF0, // 5
    0xF0, 0x80, 0xF0, 0x90, 0xF0, // 6
    0xF0, 0x10, 0x20, 0x40, 0x40, // 7
    0xF0, 0x90, 0xF0, 0x90, 0xF0, // 8
    0xF0, 0x90, 0xF0, 0x10, 0xF0, // 9
    0xF0, 0x90, 0xF0, 0x90, 0x90, // A
    0xE0, 0x90, 0xE0, 0x90, 0xE0, // B
    0xF0, 0x80, 0x80, 0x80, 0xF0, // C
    0xE0, 0x90, 0x90, 0x90, 0xE0, // D
    0xF0, 0x80, 0xF0, 0x80, 0xF0, // E
    0xF0, 0x80, 0xF0, 0x80, 0x80, // F
];

pub struct Memory {
    pub bytes: [u8; 4096],
    pub stack: Vec<usize>,
}

impl Memory {
    pub fn new() -> Self {
        let bytes = [0_u8; 4096];
        let stack = Vec::new();

        Self { bytes, stack }
    }

    pub fn load_bytes(&mut self, bytes: &[u8], offset: &usize) {
        for (i, byte) in bytes.iter().enumerate() {
            self.bytes[offset + i] = *byte;
        }
    }

    pub fn get_byte(&self, offset: usize) -> u8 {
        self.bytes[offset]
    }
}
